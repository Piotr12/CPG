import { describe, expect, it } from "vitest";
import * as db from "./index";

describe("@cpg/db", () => {
  it("exports the public API", () => {
    expect(Object.keys(db).sort()).toEqual([
      "API_TOKEN_NAME_MAX",
      "AUDIT_APPEND_ONLY",
      "AUDIT_CHANNELS",
      "ApiToken",
      "BOM_REVISION_IMMUTABLE",
      "Bom",
      "BomComponent",
      "BomRevision",
      "Customer",
      "GLOBAL_ENTITIES",
      "GlobalAuditEvent",
      "GlobalIdempotencyKey",
      "IDEMPOTENCY_KEY_MAX",
      "LOCALES",
      "Location",
      "LockWaitTimeoutException",
      "MATERIAL_DESCRIPTION_MAX",
      "MATERIAL_TYPES",
      "MATERIAL_UNIT_MAX",
      "Material",
      "MaterialConversion",
      "NAMED_RECORD_NAME_MAX",
      "OptimisticLockError",
      "PROCUREMENT_MODES",
      "PlanningParameterSet",
      "STOCK_MOVEMENT_IMMUTABLE",
      "SafetyStockTarget",
      "Session",
      "Setting",
      "StockBalance",
      "StockMovement",
      "Supplier",
      "TENANT_CODES",
      "TENANT_FILTER",
      "THEMES",
      "Tenant",
      "TenantAuditEvent",
      "TenantIdempotencyKey",
      "TenantViolationError",
      "USER_ROLES",
      "UniqueConstraintViolationException",
      "User",
      "UserPreference",
      "createOrmConfig",
      "currentTenant",
      "entities",
      "getMigrationStatus",
      "initOrm",
      "isTenantOwned",
      "migrate",
      "selectTenant",
      "tenantOwned",
    ]);
    expect(db.entities).toEqual([
      db.Setting,
      db.User,
      db.Session,
      db.UserPreference,
      db.Tenant,
      db.ApiToken,
      db.GlobalAuditEvent,
      db.TenantAuditEvent,
      db.GlobalIdempotencyKey,
      db.TenantIdempotencyKey,
      db.Material,
      db.MaterialConversion,
      db.Location,
      db.Customer,
      db.Supplier,
      db.PlanningParameterSet,
      db.SafetyStockTarget,
      db.Bom,
      db.BomRevision,
      db.BomComponent,
      db.StockBalance,
      db.StockMovement,
    ]);
    const tenantOwned: unknown[] = [
      db.TenantAuditEvent,
      db.TenantIdempotencyKey,
      db.Material,
      db.MaterialConversion,
      db.Location,
      db.Customer,
      db.Supplier,
      db.PlanningParameterSet,
      db.SafetyStockTarget,
      db.Bom,
      db.BomRevision,
      db.BomComponent,
      db.StockBalance,
      db.StockMovement,
    ];
    expect(db.GLOBAL_ENTITIES).toEqual(db.entities.filter((entity) => !tenantOwned.includes(entity)));
  });
});
