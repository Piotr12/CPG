/**
 * Migration CLI, run with tsx from the repo root:
 *
 *   npm run db:migrate                         apply pending migrations
 *   npm run db:migration:create -- <name>      diff entities against the schema snapshot and
 *                                              write a new migration + regenerate the index
 */
import { readdirSync, readFileSync, writeFileSync } from "node:fs";
import path from "node:path";
import { loadConfig } from "@cpg/core";
import { initOrm } from "../src/orm";

const migrationsDir = path.join(import.meta.dirname, "../src/migrations");
const [command, name] = process.argv.slice(2);

const orm = await initOrm(loadConfig(), {
  migrations: { path: migrationsDir, pathTs: migrationsDir, snapshotName: ".snapshot" },
});

try {
  if (command === "up") {
    const applied = await orm.migrator.up();
    console.log(applied.length ? `Applied: ${applied.map((m) => m.name).join(", ")}` : "Nothing to migrate.");
  } else if (command === "create") {
    const result = await orm.migrator.create(migrationsDir, false, false, name);
    if (result.fileName) {
      writeIndex();
      console.log(`Created ${path.join(migrationsDir, result.fileName)}`);
    } else {
      console.log("No schema changes, no migration created.");
    }
  } else {
    console.error("Usage: migrations.ts up | create [name]");
    process.exitCode = 1;
  }
} finally {
  await orm.close();
}

/** Migrations are listed explicitly (see config.ts), so every new file must land in index.ts. */
function writeIndex() {
  const files = readdirSync(migrationsDir)
    .filter((file) => /^Migration.*\.ts$/.test(file))
    .sort();
  const classes = files.map((file) => {
    const match = /export class (\w+)/.exec(readFileSync(path.join(migrationsDir, file), "utf8"));
    if (!match) throw new Error(`No exported migration class in ${file}`);
    return { file: file.replace(/\.ts$/, ""), className: match[1] };
  });

  writeFileSync(
    path.join(migrationsDir, "index.ts"),
    [
      "// Generated by `npm run db:migration:create` — do not edit by hand.",
      ...classes.map(({ file, className }) => `import { ${className} } from "./${file}";`),
      "",
      `export const migrations = [${classes.map(({ className }) => className).join(", ")}];`,
      "",
    ].join("\n"),
  );
}
